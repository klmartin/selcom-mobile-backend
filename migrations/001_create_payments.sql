CREATE TABLE IF NOT EXISTS payments (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  payment_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  merchant_reference VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  selcom_order_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  selcom_transid VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  idempotency_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  customer_name VARCHAR(150) NOT NULL,
  customer_email VARCHAR(254) NOT NULL,
  customer_phone VARCHAR(20) NOT NULL,
  amount DECIMAL(18,2) NOT NULL,
  currency CHAR(3) NOT NULL DEFAULT 'TZS',
  description VARCHAR(250) NOT NULL DEFAULT '',
  status VARCHAR(32) NOT NULL DEFAULT 'pending',
  initiation_stage VARCHAR(32) NOT NULL DEFAULT 'recorded',
  provider_payment_status VARCHAR(32) NULL,
  provider_reference VARCHAR(128) NULL,
  provider_result_code VARCHAR(32) NULL,
  provider_message VARCHAR(250) NULL,
  manual_review BOOLEAN NOT NULL DEFAULT FALSE,
  reconciliation_attempts INT UNSIGNED NOT NULL DEFAULT 0,
  reconcile_token CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  reconcile_until DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  paid_at DATETIME(6) NULL,
  last_checked_at DATETIME(6) NULL,
  next_check_at DATETIME(6) NULL,
  UNIQUE KEY uq_payment_uuid (payment_id),
  UNIQUE KEY uq_merchant_reference (merchant_reference),
  UNIQUE KEY uq_selcom_order (selcom_order_id),
  UNIQUE KEY uq_selcom_transid (selcom_transid),
  UNIQUE KEY uq_idempotency (idempotency_key),
  KEY idx_status_date (status, created_at),
  KEY idx_status_due (status, next_check_at),
  KEY idx_provider_reference (provider_reference),
  CONSTRAINT chk_amount CHECK (amount > 0),
  CONSTRAINT chk_currency CHECK (currency = 'TZS'),
  CONSTRAINT chk_payment_status CHECK (status IN ('pending','awaiting_authorization','succeeded','failed','cancelled','unresolved'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS payment_attempts (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  payment_id BIGINT UNSIGNED NOT NULL,
  operation VARCHAR(32) NOT NULL,
  request_payload JSON NULL,
  response_payload JSON NULL,
  http_status SMALLINT UNSIGNED NULL,
  transport_error_code VARCHAR(64) NULL,
  duration_ms INT UNSIGNED NULL,
  started_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  finished_at DATETIME(6) NULL,
  KEY idx_attempt_payment (payment_id, started_at),
  CONSTRAINT fk_attempt_payment FOREIGN KEY (payment_id) REFERENCES payments(id) ON DELETE RESTRICT,
  CONSTRAINT chk_attempt_operation CHECK (operation IN ('create_order','wallet_payment','status_query'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS webhook_events (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  payment_id BIGINT UNSIGNED NULL,
  dedupe_key CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  payload JSON NOT NULL,
  verification_status VARCHAR(16) NOT NULL,
  processing_status VARCHAR(32) NOT NULL,
  received_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  processed_at DATETIME(6) NULL,
  error_message VARCHAR(250) NULL,
  UNIQUE KEY uq_webhook_dedupe (dedupe_key),
  KEY idx_webhook_payment (payment_id, received_at),
  CONSTRAINT fk_webhook_payment FOREIGN KEY (payment_id) REFERENCES payments(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
